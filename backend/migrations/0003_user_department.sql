-- 0003_user_department.sql
-- ربط حساب الموظف بإدارة واحدة، وتطبيق عزل بيانات الإدارات.
-- ملاحظات التصميم:
--   * الحقل اختياري في القاعدة لأن الحسابات القديمة ومديري النظام قد يبقون بلا إدارة،
--     لكن التطبيق يفرض إدارة نشطة عند إنشاء موظف أو تحويل مدير إلى موظف.
--   * لا تُنشأ أي إدارة افتراضية ولا يُسنَد أي حساب أو مستند قديم تلقائياً؛
--     يبقى المستخدمون القدامى بلا إدارة حتى يحدد المدير الإدارة الصحيحة.
--   * ON DELETE RESTRICT يمنع حذف إدارة مرتبطة بحسابات، إضافة إلى منع حذف إدارة
--     مرتبطة بمستندات (القيد الموجود في 0001). يبقى الحذف ممكناً بعد نقل الارتباطات.
--   * الفهرس يخدم فحوص الإدارة والتقارير وعدادات الموظفين.
--   * الترحيل إضافي فقط: لا يغيّر أي صف قائم ولا يعدّل ترحيلاً سابقاً.

ALTER TABLE users
  ADD COLUMN department_id uuid REFERENCES departments(id) ON DELETE RESTRICT;

CREATE INDEX users_department_idx ON users (department_id);
